setwd("C:/Users/lshpaner/Documents/RProjects/kfre_r/paper")

pdflatex <- "C:\\Users\\lshpaner\\AppData\\Roaming\\TinyTeX\\bin\\windows\\pdflatex.exe"
bibtex   <- "C:\\Users\\lshpaner\\AppData\\Roaming\\TinyTeX\\bin\\windows\\bibtex.exe"

# ?????? Step 1: Render Rmd ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
tryCatch(
  rmarkdown::render("kfre-paper.Rmd",
                    output_format = rjtools::rjournal_article()),
  error = function(e) message("Render error (expected): ", e$message)
)

# ?????? Step 2: Fix kfre-paper.tex ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
lines <- readLines("kfre-paper.tex")
lines <- lines[!grepl("\\\\bibliography\\{", lines)]
lines <- lines[!grepl("\\\\section\\*\\{References\\}", lines)]
lines <- lines[!grepl("\\\\addcontentsline\\{toc\\}\\{section\\}\\{References\\}", lines)]
lines <- gsub("{kfre-paper_files/figure-latex/risk-by-stage-1}",
              "{kfre-paper_files/figure-latex/risk-by-stage-1.png}", lines, fixed = TRUE)
lines <- gsub("{kfre-paper_files/figure-latex/model-comparison-1}",
              "{kfre-paper_files/figure-latex/model-comparison-1.png}", lines, fixed = TRUE)
addr_idx <- grep("\\\\address\\{", lines)
lines <- append(lines, "\\bibliography{kfre}", after = addr_idx[1] - 1)
writeLines(lines, "kfre-paper.tex")

# ?????? Step 3: Copy figures ???????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
dir.create("kfre-paper_files/figure-latex", showWarnings = FALSE)
file.copy("kfre-paper_files/figure-html5/risk-by-stage-1.png",
          "kfre-paper_files/figure-latex/risk-by-stage-1.png", overwrite = TRUE)
file.copy("kfre-paper_files/figure-html5/model-comparison-1.png",
          "kfre-paper_files/figure-latex/model-comparison-1.png", overwrite = TRUE)

# ?????? Step 4: Fix RJwrapper.tex - remove bibliography + add refname fix ????????????????????????
lines <- readLines("RJwrapper.tex")
lines <- lines[!grepl("\\\\bibliography\\{", lines)]
# Add \renewcommand{\refname}{References} before \begin{document}
begin_idx <- grep("\\\\begin\\{document\\}", lines)
lines <- append(lines, "\\renewcommand{\\refname}{References}",
                after = begin_idx[1] - 1)
writeLines(lines, "RJwrapper.tex")

# ?????? Step 5: Delete stale aux files ?????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
invisible(file.remove(list.files(".", pattern = "RJwrapper\\.(aux|bbl|blg|brf|out)$",
                                 full.names = TRUE)))

# ?????? Step 6: Four-pass compile ????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
system(paste(shQuote(pdflatex), "-interaction=nonstopmode RJwrapper.tex"))
system(paste(shQuote(bibtex), "RJwrapper"))
system(paste(shQuote(pdflatex), "-interaction=nonstopmode RJwrapper.tex"))
system(paste(shQuote(pdflatex), "-interaction=nonstopmode RJwrapper.tex"))

message("Done! RJwrapper.pdf is ready.")